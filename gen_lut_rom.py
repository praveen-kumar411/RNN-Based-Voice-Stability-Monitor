# gen_lut_rom.py : writes act_lut_syn.v (synthesizable, same behaviour as act_lut.v)
from fxp import SIG_LUT

lines = []
lines.append("`timescale 1ns/1ps")
lines.append("// act_lut_syn: synthesizable sigmoid/tanh LUT (generated by gen_lut_rom.py)")
lines.append("module act_lut (")
lines.append("  input  wire               mode,")
lines.append("  input  wire signed [15:0] x_in,")
lines.append("  output reg  signed [15:0] y_out")
lines.append(");")
lines.append("  wire signed [16:0] x_ext   = {x_in[15], x_in};")
lines.append("  wire signed [16:0] x_sel   = mode ? (x_ext <<< 1) : x_ext;")
lines.append("  wire signed [16:0] x_clamp = (x_sel >  17'sd16383) ?  17'sd16383 :")
lines.append("                               (x_sel < -17'sd16384) ? -17'sd16384 : x_sel;")
lines.append("  wire signed [16:0] x_sh = x_clamp >>> 7;")
lines.append("  wire [7:0] idx = x_sh[7:0] + 8'd128;")
lines.append("  reg  signed [15:0] sig;")
lines.append("  always @(*) case (idx)")
for i, v in enumerate(SIG_LUT):
    lines.append(f"    8'd{i}: sig = 16'sd{v};")
lines.append("    default: sig = 16'sd0;")
lines.append("  endcase")
lines.append("  always @(*) y_out = mode ? ((sig <<< 1) - 16'sd2048) : sig;")
lines.append("endmodule")

with open("act_lut_syn.v", "w") as f:
    f.write("\n".join(lines) + "\n")
print("Wrote act_lut_syn.v")
